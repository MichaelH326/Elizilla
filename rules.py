"""
Rules are written in terms of sentence sections and word categories.

Each rule has:
  when    - what the clause must contain (see the keys below)
  say     - reply templates
  weight  - base priority
  mood    - (optional) the mood the rule suits: "low", "positive", "neutral"

`when` keys (a value can be one option or a tuple of options):
  who        subject category        "@self", "@family", "@they", ...
  mine       subject is "my ..."     True
  action     verb category or lemma  "@dislike", "quit"
  not        negated                 True / False
  modal      helper verb             "can", "will", "should"
  describer  adjective category      "@sad", "@busy", or "any"
  what       object category         "@task", "@timeamt", or "any"
  follow     follow-on clause type   "to", "that", "when", "ing", "like", "about", or "any"
  joined     conjunction before the clause   "but", "because"
  has        a category anywhere in the clause   "@family"
  fragment   no verb at all          True
  pair       two or more nouns with no verb       True
  question   it's a question         True

Template slots (already flipped to the bot's point of view, "my" -> "your"):
  {who} {whom} {action} {acting} {what} {describer} {follow} {rest} {says}
  {when} {topic} {n1} {n2} {before} {clause}
"""

